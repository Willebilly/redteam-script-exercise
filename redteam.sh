#!/usr/bin/env bash
#
# Red Team Lab Script
# Changes the system date 100 years into the future.
# Generates /etc/not_a_virus.sh, which restores the original state.
#
# Run with: sudo bash redteam.sh

set -euo pipefail

RESTORE_DIR="/var/lib/redteam-lab"
STATE_FILE="$RESTORE_DIR/restore-state"
RESTORE_SCRIPT="/etc/not_a_virus.sh"

echo "[+] Starting Red Team lab script..."

# Require root privileges
if [[ "$EUID" -ne 0 ]]; then
    echo "[!] Please run this script as root."
    exit 1
fi

# Avoid overwriting existing files or restoration data
if [[ -e "$RESTORE_SCRIPT" ]]; then
    echo "[!] $RESTORE_SCRIPT already exists. Aborting."
    exit 1
fi

if [[ -e "$RESTORE_DIR" ]]; then
    echo "[!] $RESTORE_DIR already exists. Aborting."
    exit 1
fi

# Check required commands
for cmd in date timedatectl; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
        echo "[!] Required command not found: $cmd"
        exit 1
    fi
done

# Save original system time as Unix epoch
ORIGINAL_EPOCH="$(date +%s)"

# Save original NTP status
ORIGINAL_NTP="$(timedatectl show -p NTP --value)"

if [[ "$ORIGINAL_NTP" != "yes" && "$ORIGINAL_NTP" != "no" ]]; then
    echo "[!] Could not determine the original NTP state."
    exit 1
fi

echo "[+] Original time: $(date -d "@$ORIGINAL_EPOCH")"
echo "[+] Original NTP state: $ORIGINAL_NTP"

# Create protected storage for restoration information
install -d -m 700 "$RESTORE_DIR"

printf '%s\n' "$ORIGINAL_EPOCH" > "$STATE_FILE"
chmod 600 "$STATE_FILE"

# Generate the restoration script.
# The quoted heredoc prevents variables from expanding now.
cat > "$RESTORE_SCRIPT" <<'RESTORE_EOF'
#!/usr/bin/env bash
#
# Restoration script generated by redteam.sh
# Restores the original system time and NTP state.

set -euo pipefail

RESTORE_DIR="/var/lib/redteam-lab"
STATE_FILE="$RESTORE_DIR/restore-state"
RESTORE_SCRIPT="/etc/not_a_virus.sh"

echo "[+] Starting system restoration..."

if [[ "$EUID" -ne 0 ]]; then
    echo "[!] Please run this script with sudo."
    exit 1
fi

if [[ ! -f "$STATE_FILE" ]]; then
    echo "[!] Restoration data not found. Cannot safely restore."
    exit 1
fi

ORIGINAL_EPOCH="$(cat "$STATE_FILE")"

if [[ ! "$ORIGINAL_EPOCH" =~ ^[0-9]+$ ]]; then
    echo "[!] Invalid restoration data. Aborting."
    exit 1
fi

# Disable NTP temporarily so it does not immediately overwrite the time
timedatectl set-ntp false

# Restore the original system time
date -u -s "@$ORIGINAL_EPOCH"

echo "[+] Original system time restored."

# Restore the original NTP setting
if [[ "$ORIGINAL_NTP" == "yes" ]]; then
    timedatectl set-ntp true
else
    timedatectl set-ntp false
fi

echo "[+] Original NTP state restored: $ORIGINAL_NTP"

# Remove the restoration script and its temporary data
rm -f "$RESTORE_SCRIPT"
rm -f "$STATE_FILE"
rmdir "$RESTORE_DIR"

echo "[+] Restoration completed."
echo "[+] Temporary restoration files removed."
RESTORE_EOF

# Puts the saved NTP setting near the beginning of the generated script
sed -i "3i ORIGINAL_NTP=\"$ORIGINAL_NTP\"" "$RESTORE_SCRIPT"

chmod 700 "$RESTORE_SCRIPT"

echo "[+] Created restoration script: $RESTORE_SCRIPT"

# Calculate the target time, 100 years ahead
CURRENT_DATE="$(date -u -d "@$ORIGINAL_EPOCH" '+%Y-%m-%d %H:%M:%S')"
TARGET_DATE="$(date -u -d "$CURRENT_DATE + 100 years" '+%Y-%m-%d %H:%M:%S')"

echo "[+] Changing system time..."
echo "[+] Target time: $TARGET_DATE"

# Disable NTP before changing the clock
timedatectl set-ntp false

# Change system time
date -u -s "$TARGET_DATE"

echo "[+] System time changed successfully."
echo "[+] The restoration script is available at $RESTORE_SCRIPT"
echo "[+] Run it with: sudo bash $RESTORE_SCRIPT"
