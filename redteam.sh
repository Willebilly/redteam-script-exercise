#!/usr/bin/env bash
#
# Red Team Lab Script
# Ubuntu lab exercise for MITRE ATT&CK technique simulation.
#
# Run with: sudo bash redteam.sh
# Restore with: sudo bash /etc/not_a_virus.sh

set -Eeuo pipefail
umask 077

# ============================================================
# CONFIGURATION
# ============================================================

RESTORE_DIR="/var/lib/redteam-lab"
STATE_FILE="$RESTORE_DIR/restore-state"
RESTORE_SCRIPT="/etc/not_a_virus.sh"

HIDDEN_FILE="/etc/.system_cache"
MASQUERADE_FILE="/etc/hosts-"
PERMISSION_FILE="/var/tmp/redteam-permission-test"

LOG_FILE="/var/log/redteam-lab.log"

# ============================================================
# LOGGING
# ============================================================

log() {
    local message="$1"
    printf '[%s] %s\n' "$(date -Is)" "$message" | tee -a "$LOG_FILE"
}

# ============================================================
# PRE-FLIGHT CHECKS
# ============================================================

require_root() {
    if [[ "$EUID" -ne 0 ]]; then
        echo "[!] Run this script as root."
        exit 1
    fi
}

check_dependencies() {
    local commands=(date timedatectl chmod install stat uname id hostname)

    for cmd in "${commands[@]}"; do
        if ! command -v "$cmd" >/dev/null 2>&1; then
            echo "[!] Missing required command: $cmd"
            exit 1
        fi
    done
}

check_existing_files() {
    local paths=(
        "$RESTORE_DIR"
        "$RESTORE_SCRIPT"
        "$HIDDEN_FILE"
        "$MASQUERADE_FILE"
        "$PERMISSION_FILE"
    )

    for path in "${paths[@]}"; do
        if [[ -e "$path" ]]; then
            echo "[!] $path already exists. Aborting to avoid overwriting."
            exit 1
        fi
    done
}

# ============================================================
# COLLECT ORIGINAL SYSTEM STATE
# ============================================================

save_original_state() {
    ORIGINAL_EPOCH="$(date +%s)"
    ORIGINAL_NTP="$(timedatectl show -p NTP --value)"

    if [[ "$ORIGINAL_NTP" != "yes" && "$ORIGINAL_NTP" != "no" ]]; then
        echo "[!] Could not determine original NTP state."
        exit 1
    fi

    CURRENT_DATE="$(date -u -d "@$ORIGINAL_EPOCH" '+%Y-%m-%d %H:%M:%S')"

    TARGET_DATE="$(date -u -d "$CURRENT_DATE + 1 year" '+%Y-%m-%d %H:%M:%S')"

    if [[ -z "$TARGET_DATE" ]]; then
        echo "[!] Could not calculate target date."
        exit 1
    fi

    log "Original system time: $CURRENT_DATE UTC"
    log "Original NTP state: $ORIGINAL_NTP"
    log "Target system time: $TARGET_DATE UTC"
}

# ============================================================
# SAVE RESTORATION DATA
# ============================================================

create_restore_state() {
    install -d -m 700 "$RESTORE_DIR"

    {
        printf '%s\n' "$ORIGINAL_EPOCH"
        printf '%s\n' "$ORIGINAL_NTP"
    } > "$STATE_FILE"

    chmod 600 "$STATE_FILE"

    log "Original system state saved."
}

# ============================================================
# GENERATE RESTORATION SCRIPT
# ============================================================

generate_restore_script() {
    cat > "$RESTORE_SCRIPT" <<'RESTORE_EOF'
#!/usr/bin/env bash
#
# Generated by redteam.sh
# Restores the original system time and NTP state.
# Removes the lab artifacts created by redteam.sh.

set -Eeuo pipefail

RESTORE_DIR="/var/lib/redteam-lab"
STATE_FILE="$RESTORE_DIR/restore-state"
RESTORE_SCRIPT="/etc/not_a_virus.sh"

HIDDEN_FILE="/etc/.system_cache"
MASQUERADE_FILE="/etc/hosts-"
PERMISSION_FILE="/var/tmp/redteam-permission-test"

LOG_FILE="/var/log/redteam-lab.log"

log() {
    printf '[%s] %s\n' "$(date -Is)" "$1" | tee -a "$LOG_FILE"
}

if [[ "$EUID" -ne 0 ]]; then
    echo "[!] Run this script as root."
    exit 1
fi

if [[ ! -f "$STATE_FILE" ]]; then
    echo "[!] Restoration data not found. Aborting."
    exit 1
fi

# Read and validate saved state
mapfile -t STATE < "$STATE_FILE"

if [[ "${#STATE[@]}" -ne 2 ]]; then
    echo "[!] Invalid restoration data."
    exit 1
fi

ORIGINAL_EPOCH="${STATE[0]}"
ORIGINAL_NTP="${STATE[1]}"

if [[ ! "$ORIGINAL_EPOCH" =~ ^[0-9]+$ ]]; then
    echo "[!] Invalid original timestamp."
    exit 1
fi

if [[ "$ORIGINAL_NTP" != "yes" && "$ORIGINAL_NTP" != "no" ]]; then
    echo "[!] Invalid original NTP state."
    exit 1
fi

log "Starting restoration."

# Disable NTP before setting the original clock
timedatectl set-ntp false

# Restore original system time
date -u -s "@$ORIGINAL_EPOCH" >/dev/null

log "Original system time restored."

# Restore original NTP configuration
if [[ "$ORIGINAL_NTP" == "yes" ]]; then
    timedatectl set-ntp true
else
    timedatectl set-ntp false
fi

log "Original NTP state restored: $ORIGINAL_NTP"

# Remove lab artifacts
rm -f -- "$HIDDEN_FILE"
rm -f -- "$MASQUERADE_FILE"
rm -f -- "$PERMISSION_FILE"

log "Lab test files removed."

# Remove temporary restoration information
rm -f -- "$STATE_FILE"
rmdir "$RESTORE_DIR"

log "Temporary restoration data removed."

# Remove the restoration script itself
rm -f -- "$RESTORE_SCRIPT"

log "Restoration completed successfully."
log "The lab log has been retained at $LOG_FILE"
RESTORE_EOF

    chmod 700 "$RESTORE_SCRIPT"

    # Validate generated script before changing system state
    bash -n "$RESTORE_SCRIPT"

    log "Restoration script generated and syntax-checked."
}

# ============================================================
# MITRE T1059.004 - UNIX SHELL
# ============================================================

execute_bash_actions() {
    log "T1059.004: Executing Unix shell commands."
    log "Script interpreter: $BASH"
}

# ============================================================
# MITRE T1564.001 - HIDDEN FILES AND DIRECTORIES
# ============================================================

create_hidden_file() {
    install -m 600 /dev/null "$HIDDEN_FILE"

    printf '%s\n' "Red Team lab hidden test file." > "$HIDDEN_FILE"

    log "T1564.001: Created hidden file: $HIDDEN_FILE"
}

# ============================================================
# MITRE T1036.005 - MATCH LEGITIMATE RESOURCE NAME OR LOCATION
# ============================================================

create_masquerade_file() {
    install -m 644 /dev/null "$MASQUERADE_FILE"

    cat > "$MASQUERADE_FILE" <<'EOF'
# Red Team lab marker.
# This is NOT a real hosts backup file.
EOF

    log "T1036.005: Created masquerade test file: $MASQUERADE_FILE"
}

# ============================================================
# MITRE T1222.002 - LINUX FILE PERMISSIONS MODIFICATION
# ============================================================

modify_file_permissions() {
    # Create file with normal read permissions
    install -m 644 /dev/null "$PERMISSION_FILE"

    printf '%s\n' "Permission modification test." > "$PERMISSION_FILE"

    log "T1222.002: Initial permissions: $(stat -c '%a' "$PERMISSION_FILE")"

    # Change permissions
    chmod 600 "$PERMISSION_FILE"

    log "T1222.002: Modified permissions: $(stat -c '%a' "$PERMISSION_FILE")"
}

# ============================================================
# MITRE T1082 - SYSTEM INFORMATION DISCOVERY
# ============================================================

collect_system_information() {
    log "T1082: Collecting system information."

    {
        echo "========== SYSTEM INFORMATION =========="
        echo "Hostname:"
        hostname

        echo
        echo "Kernel:"
        uname -a

        echo
        echo "Operating system:"
        if [[ -f /etc/os-release ]]; then
            cat /etc/os-release
        fi

        echo
        echo "Architecture:"
        uname -m
        echo "========================================="
    } >> "$LOG_FILE"
}

# ============================================================
# MITRE T1033 - SYSTEM OWNER / USER DISCOVERY
# ============================================================

collect_user_information() {
    log "T1033: Collecting user information."

    {
        echo "========== USER INFORMATION ============="
        echo "Current user:"
        whoami

        echo
        echo "User ID and groups:"
        id

        echo
        echo "Groups:"
        groups

        echo "=========================================="
    } >> "$LOG_FILE"
}

# ============================================================
# CHANGE SYSTEM TIME
# ============================================================

change_system_time() {
    log "Disabling NTP temporarily."

    timedatectl set-ntp false

    log "Changing system time 1 years into the future."

    date -u -s "$TARGET_DATE" >/dev/null

    log "System time changed successfully."
    log "Current system time: $(date -u)"
}

# ============================================================
# MAIN EXECUTION
# ============================================================

main() {
    require_root

    # Initialize log
    touch "$LOG_FILE"
    chmod 600 "$LOG_FILE"

    log "=========================================="
    log "Starting Red Team lab script."
    log "=========================================="

    check_dependencies
    check_existing_files

    save_original_state
    create_restore_state
    generate_restore_script

    # Execute lab actions
    execute_bash_actions
    create_hidden_file
    create_masquerade_file
    modify_file_permissions
    collect_system_information
    collect_user_information

    # Change system time last
    change_system_time

    log "=========================================="
    log "Red Team lab execution completed."
    log "Restoration script: $RESTORE_SCRIPT"
    log "Run: sudo bash $RESTORE_SCRIPT"
    log "Log file: $LOG_FILE"
    log "=========================================="
}

main "$@"



